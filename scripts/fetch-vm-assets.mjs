/**
 * Stages the assets VirtualBoks needs to emulate a PC into
 * `windoes/public/applications/virtualboks/vendor/` (git-ignored).
 *
 * Two different kinds of asset, two different sources:
 *
 * - The v86 emulator core (`libv86.js` + the WebAssembly CPU) ships in the
 *   `v86` npm package, so it is copied straight out of `node_modules`.
 * - The firmware blobs (SeaBIOS + VGABIOS) are *not* published to npm. They
 *   are downloaded from the upstream v86 repository and pinned by SHA-256,
 *   which keeps LGPL-licensed binaries out of this repository's history while
 *   still making the download verifiable. See `vendor/NOTICE.md`.
 *
 * Runs from `postinstall`. A failure here must never break `npm ci`: the app
 * detects missing assets and explains how to fetch them, so we warn and exit 0
 * unless `--strict` is passed (used by CI when the assets are required).
 */
import { createHash } from 'node:crypto';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const ROOT = fileURLToPath(new URL('..', import.meta.url));
const VENDOR_DIR = path.join(ROOT, 'windoes/public/applications/virtualboks/vendor');
const V86_BUILD_DIR = path.join(ROOT, 'node_modules/v86/build');

// Upstream commit-independent pin: the firmware is fetched from the v86 default
// branch and rejected unless it hashes to exactly these bytes. If upstream
// rebuilds its firmware the download fails loudly with the new digest, which is
// the signal to review the change and update the pin here.
const BIOS_BASE_URL = 'https://raw.githubusercontent.com/copy/v86/master/bios';
const BIOS_FILES = [
  {
    name: 'seabios.bin',
    sha256: '73e3f359102e3a9982c35fce98eb7cd08f18303ac7f1ba6ebfbe6cdc1c244d98',
    bytes: 131072,
  },
  {
    name: 'vgabios.bin',
    sha256: 'a4bc0d80cc3ca028c73dafa8fee396b8d054ce87ebd8abfbd31b06b437607880',
    bytes: 36352,
  },
];

// Copied verbatim out of the npm package. `libv86.js` is the classic-script
// build (it assigns `window.V86`), which is what the app loads on demand.
const V86_FILES = ['libv86.js', 'v86.wasm', 'v86-fallback.wasm'];

const NOTICE = `# Third-party binaries

This directory is generated by \`scripts/fetch-vm-assets.mjs\` and is not checked
into git. It holds the PC emulator that the VirtualBoks application runs.

## v86 (\`libv86.js\`, \`v86.wasm\`, \`v86-fallback.wasm\`)

Copied from the \`v86\` npm package. v86 is distributed under the Simplified BSD
License. Source: https://github.com/copy/v86

## SeaBIOS (\`seabios.bin\`)

Downloaded from the v86 repository, which redistributes a SeaBIOS build.
SeaBIOS is licensed under the LGPLv3. Source: https://github.com/coreboot/seabios

## VGABIOS (\`vgabios.bin\`)

Downloaded from the v86 repository. Licensed under the LGPLv2.1 or later.
Source: https://github.com/qemu/vgabios
`;

const strict = process.argv.includes('--strict');

function sha256(buffer) {
  return createHash('sha256').update(buffer).digest('hex');
}

async function copyEmulatorCore() {
  for (const name of V86_FILES) {
    const from = path.join(V86_BUILD_DIR, name);
    let contents;
    try {
      contents = await readFile(from);
    } catch {
      throw new Error(
        `missing ${path.relative(ROOT, from)} — run \`npm install\` so the v86 package is present`
      );
    }
    await writeFile(path.join(VENDOR_DIR, name), contents);
    console.log(`  v86      ${name} (${contents.length.toLocaleString()} bytes)`);
  }
}

async function downloadFirmware() {
  for (const file of BIOS_FILES) {
    const target = path.join(VENDOR_DIR, file.name);

    // Already staged and intact: skip the network entirely so repeat installs
    // and offline rebuilds stay fast.
    try {
      const existing = await readFile(target);
      if (sha256(existing) === file.sha256) {
        console.log(`  firmware ${file.name} (cached)`);
        continue;
      }
    } catch {
      // Not staged yet — fall through to the download.
    }

    const url = `${BIOS_BASE_URL}/${file.name}`;
    const response = await fetch(url);
    if (!response.ok) {
      throw new Error(`${url} responded ${response.status} ${response.statusText}`);
    }

    const contents = Buffer.from(await response.arrayBuffer());
    const digest = sha256(contents);
    if (digest !== file.sha256) {
      throw new Error(
        `${file.name} does not match its pinned checksum.\n` +
          `    expected ${file.sha256}\n` +
          `    received ${digest}\n` +
          `    Review the upstream change before updating the pin in ${path.relative(ROOT, fileURLToPath(import.meta.url))}.`
      );
    }

    await writeFile(target, contents);
    console.log(`  firmware ${file.name} (${contents.length.toLocaleString()} bytes)`);
  }
}

async function main() {
  await mkdir(VENDOR_DIR, { recursive: true });
  await copyEmulatorCore();
  await downloadFirmware();
  await writeFile(path.join(VENDOR_DIR, 'NOTICE.md'), NOTICE);
  console.log('VirtualBoks assets ready.');
}

main().catch((error) => {
  const message = error?.message || String(error);
  if (strict) {
    console.error(`\nFailed to stage VirtualBoks assets: ${message}`);
    process.exit(1);
  }
  console.warn(
    `\nSkipping VirtualBoks emulator assets: ${message}\n` +
      'The desktop still builds and runs; VirtualBoks will explain how to retry\n' +
      '(`npm run assets:vm`) instead of booting.\n'
  );
});
